lines = []
lines.append('')
lines.append('def _on_post_tool_call(tool_name, args, result, task_id, **kwargs):')
lines.append('    """Wire verification into the post_tool_call hook (v0.3.0 step 5).')
lines.append('')
lines.append('    For every ceo_* result, run verify_result and log whether it is')
lines.append('    verified. The hook never raises and never blocks the host — it')
lines.append('    closes the advisory gap by making verification visible on every')
lines.append('    call, while ceo_verify remains the tool a caller uses explicitly.')
lines.append('    """')
lines.append('    logger.debug("CEO Pack: tool called: %s (session %s)", tool_name, task_id)')
lines.append('    if not tool_name.startswith("ceo_") and tool_name != "q4_closeout_checklist":')
lines.append('        return')
lines.append('    try:')
lines.append('        from .orchestration import META_TOOLS, verify_result')
lines.append('')
lines.append('        if tool_name in META_TOOLS:')
lines.append('            # An envelope or a verdict is not a completed business action, so there is nothing to verify.')
lines.append('            logger.info("CEO Pack verify: %s is a meta tool (validation/verdict), not a completion.", tool_name)')
lines.append('            return')
lines.append('')
lines.append('        parsed = result')
lines.append('        if isinstance(result, str):')
lines.append('            try:')
lines.append('                parsed = json.loads(result)')
lines.append('            except ValueError:')
lines.append('                parsed = None')
lines.append('        verdict = verify_result(tool_name, parsed)')
lines.append('        logger.info(')
lines.append('            "CEO Pack verify: %s status=%s verified=%s next=%s",')
lines.append('            tool_name,')
lines.append('            verdict.get("status"),')
lines.append('            verdict.get("verified"),')
lines.append('            verdict.get("next", {}).get("action"),')
lines.append('        )')
lines.append('    except Exception:')
lines.append('        logger.exception("CEO Pack: post_tool_call verification failed for %s", tool_name)')
lines.append('')
lines.append('')
lines.append('def _ceo_command(raw_args):')
lines.append('    return (')
lines.append('        "CEO Pack: use ceo_brief for a goal, ceo_route to pick a seat, "')
lines.append('        "ceo_assign for one owner + one due date, and ceo_decision_log "')
lines.append('        "to record the decision. External actions need owner approval. "')
lines.append('        f"Input was: {raw_args}"')
lines.append('    )')
lines.append('')
lines.append('')
lines.append('def _q4_command(raw_args):')
lines.append('    return (')
lines.append('        "CEO Pack Q4 closeout: use q4_closeout_checklist with the year, "')
lines.append('        "then assign CFO (books/tax prep), CLO (entity/filings), "')
lines.append('        "COO/Hermes (coordination), and CRO (potential-client pipeline). "')
lines.append('        "Checklist only, not tax or legal advice. "')
lines.append('        f"Input was: {raw_args}"')
lines.append('    )')
lines.append('')

with open('__init__.py', 'a') as f:
    f.write('\n'.join(lines))
