lines = []
lines.append('def _read_install_config(ctx):')
lines.append('    """Read declared settings through the real Hermes API, ctx.get_config(key).')
lines.append('')
lines.append('    Older hosts that expose a plain dict (config / settings / plugin_config) are still honoured.')
lines.append('    """')
lines.append('    try:')
lines.append('        from . import orchestration')
lines.append('    except ImportError:')
lines.append('        import orchestration')
lines.append('    cfg = {}')
lines.append('    getter = getattr(ctx, "get_config", None)')
lines.append('    if callable(getter):')
lines.append('        for key in orchestration.CONFIG_KEYS + ("seat_names",):')
lines.append('            try:')
lines.append('                value = getter(key, None)')
lines.append('            except Exception:')
lines.append('                value = None')
lines.append('            if value is not None:')
lines.append('                cfg[key] = value')
lines.append('    if not cfg:')
lines.append('        for attr in ("config", "settings", "plugin_config"):')
lines.append('            legacy = getattr(ctx, attr, None)')
lines.append('            if isinstance(legacy, dict) and legacy:')
lines.append('                cfg = legacy')
lines.append('                break')
lines.append('    return cfg')
lines.append('')
lines.append('')
lines.append('def _apply_install_config(ctx):')
lines.append('    """Apply every declared install setting; log what was applied and what was refused."""')
lines.append('    try:')
lines.append('        from . import orchestration')
lines.append('    except ImportError:')
lines.append('        import orchestration')
lines.append('    applied, notes = orchestration.apply_install_config(_read_install_config(ctx))')
lines.append('    if applied:')
lines.append('        logger.info("CEO Pack install config applied: %s", ", ".join(applied))')
lines.append('    for note in notes:')
lines.append('        logger.warning("CEO Pack install config: %s", note)')
lines.append('')

with open('__init__.py', 'a') as f:
    f.write('\n'.join(lines))
